/**
 * Generate llms-full.txt from the contract docs, and verify llms.txt links.
 *
 *   node build/llms-full.mjs          # write llms-full.txt
 *   node build/llms-full.mjs --check  # fail if the committed file drifted,
 *                                     # or if an llms.txt GitHub link 404s
 */
import { existsSync, lstatSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { projectRoot } from './lib.mjs';

const SOURCES = [
  { path: 'AGENTS.md', title: 'AGENTS.md' },
  { path: 'DESIGN.md', title: 'DESIGN.md' },
  { path: 'README.md', title: 'README.md' },
  { path: 'docs/text.md', title: 'docs/text.md' },
  { path: 'CONTRIBUTING.md', title: 'CONTRIBUTING.md' },
];

const DEST = resolve(projectRoot, 'llms-full.txt');
const LLMS_TXT = resolve(projectRoot, 'llms.txt');
const REPO_BLOB = 'https://github.com/the-hooman-loop/konstrukt/blob/main/';
const REPO_TREE = 'https://github.com/the-hooman-loop/konstrukt/tree/main/';

const HEADER = `# Konstrukt

> The Hooman Loop design system (v2.0.0). Swiss / Bauhaus: \`--radius: 0px\`, \`--shadow: none\`, one palette (\`atelier\`), light and dark via \`data-mode\` on \`<html>\`. Tokens are authored as W3C DTCG JSON and generated into CSS, Swift/SwiftUI, \`dist/tokens.json\`, and a text/ASCII layer.

This file is generated by \`node build/llms-full.mjs\` from the documents listed below. Do not edit it by hand. After changing any of those sources, run \`npm run build:llms\` and commit the result.

Included: ${SOURCES.map((s) => s.path).join(', ')}.
`;

export function renderLlmsFull() {
  const parts = [HEADER.trimEnd(), ''];
  for (const src of SOURCES) {
    const abs = resolve(projectRoot, src.path);
    if (!existsSync(abs)) {
      throw new Error(`missing llms-full source: ${src.path}`);
    }
    const body = readFileSync(abs, 'utf8').replace(/\s+$/, '');
    parts.push('---', '', `source: ${src.path}`, '', body, '');
  }
  return `${parts.join('\n')}\n`;
}

function checkLlmsTxtLinks() {
  if (!existsSync(LLMS_TXT)) {
    throw new Error('missing llms.txt');
  }
  const text = readFileSync(LLMS_TXT, 'utf8');
  const links = [...text.matchAll(/\[([^\]]+)\]\(([^)]+)\)/g)].map((m) => ({
    label: m[1],
    href: m[2],
  }));
  if (links.length === 0) {
    throw new Error('llms.txt has no markdown links');
  }

  const missing = [];
  const skipped = [];
  for (const { label, href } of links) {
    let rel = null;
    if (href.startsWith(REPO_BLOB)) rel = decodeURIComponent(href.slice(REPO_BLOB.length));
    else if (href.startsWith(REPO_TREE)) rel = decodeURIComponent(href.slice(REPO_TREE.length));
    else if (/^https?:\/\//.test(href)) {
      skipped.push(href);
      continue;
    } else {
      rel = href.replace(/^\.\//, '');
    }
    rel = rel.split('#')[0];
    const abs = resolve(projectRoot, rel);
    if (!existsSync(abs)) {
      missing.push(`${label} → ${href} (${rel})`);
    }
  }
  if (skipped.length) {
    throw new Error(
      `llms.txt has non-GitHub URLs; link only files that resolve on GitHub:\n  ${skipped.join('\n  ')}`
    );
  }
  if (missing.length) {
    throw new Error(`llms.txt links to missing files:\n  ${missing.join('\n  ')}`);
  }
  return links.length;
}

function main() {
  const check = process.argv.includes('--check');
  const expected = renderLlmsFull();

  if (check) {
    if (!existsSync(DEST)) {
      console.error('llms-full.txt is missing. Run `npm run build:llms` and commit it.');
      process.exit(1);
    }
    const actual = readFileSync(DEST, 'utf8');
    if (actual !== expected) {
      console.error(
        'llms-full.txt is stale. Run `npm run build:llms` and commit the result.'
      );
      process.exit(1);
    }
    const n = checkLlmsTxtLinks();
    const dirs = SOURCES.filter((s) => lstatSync(resolve(projectRoot, s.path)).isFile());
    console.log(`llms-full.txt matches ${dirs.length} sources; llms.txt ${n} links resolve`);
    return;
  }

  writeFileSync(DEST, expected);
  console.log(`wrote ${DEST}`);
}

main();
